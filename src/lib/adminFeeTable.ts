const findRange = (priceMmk: number): AdminFeeRange | undefined =>
  ADMIN_FEE_RANGES.find((range) => priceMmk >= range.min && priceMmk <= range.max);

export const getAdminFee = (priceMmk: number, option: AdminFeeOption): number => {
  const range = findRange(priceMmk) ?? ADMIN_FEE_RANGES[ADMIN_FEE_RANGES.length - 1];
  return range[option];
};
